def _clave_secreta():
    archivo = DATA_DIR / 'secret.key'
    if archivo.exists():
        return archivo.read_text().strip()
    from django.core.management.utils import get_random_secret_key
    clave = get_random_secret_key()
    archivo.write_text(clave)
    return clave

